from pathlib import Path
import sys,json,math
sys.path.insert(0,str(Path('work/analysis').resolve()))
from side_profile import sample,segs
repo=Path('work/3d-workshop')
release=repo/'models/sarepta/releases/2026-10-31_fair-cover-joint'
release.mkdir(parents=True,exist_ok=True)
# Sample the actual outer skin at the horizontal join. Preserve the lower mesh.
xs={2.3441,170.0}
xs.update(2.5+i*.25 for i in range(670))
# Include existing plan knuckles, but avoid float-sized intervals.
xs.update(round(p[0],4) for (ps,s) in segs for p in ps if 2.3441<p[0]<170)
ordered=sorted(xs);xs=[]
for x in ordered:
 if not xs or x-xs[-1]>=.015:xs.append(x)
if xs[-1]!=170:xs.append(170)
rows=[]
for x in xs:
 r=sample(min(x,169.999999))
 if r is None:raise ValueError(x)
 y,s=r
 rows.append([x,y+s*.001,s])
# The upper skin is a ruled continuation at each X, without a vertical lift.
# Its positive half extends to negative Y, then is clipped at the centreplane.
# This also gives a naturally raked, closed bow tip at the raised roof.
points=[];n=len(rows)
for z in [25,30.117391304347826]:
 for x,y,s in rows:points.append([x,y+s*(z-25),z])
 for x,y,s in rows:points.append([x,-100,z])
faces=[]
def quad(a,b,c,d):faces.extend([[a,b,c],[a,c,d]])
for i in range(n-1):
 quad(i,i+1,2*n+i+1,2*n+i)
 quad(n+i,3*n+i,3*n+i+1,n+i+1)
 quad(i,n+i,n+i+1,i+1)
 quad(2*n+i,2*n+i+1,3*n+i+1,3*n+i)
quad(0,2*n,3*n,n)
quad(n-1,2*n-1,4*n-1,3*n-1)
# OpenSCAD uses clockwise faces viewed from outside. Check generated orientation.
volume=0
for f in faces:
 a,b,c=[points[j] for j in f]
 volume+=sum(a[i]*(b[(i+1)%3]*c[(i+2)%3]-b[(i+2)%3]*c[(i+1)%3]) for i in range(3))/6
if volume>0:faces=[f[::-1] for f in faces]
text='// Derived from unchanged lightweight lower STL, at Z=25 mm.\n'
text+='// Rows are X, external Y at the join, and local dY/dZ.\n'
text+='// Generated by build_continuation.py; dimensions are model millimetres.\n'
text+='join_profile = '+json.dumps(rows,separators=(',',':'))+';\n'
text+='module continuation_half() {\n polyhedron(points='+json.dumps(points,separators=(',',':'))+',\n faces='+json.dumps(faces,separators=(',',':'))+', convexity=40);\n}\n'
text+='module continuation_blank() {\n union() {\n for (side=[0,1]) mirror([0,side,0]) intersection() {\n continuation_half();\n translate([-5,0,24.99]) cube([180,50,5.14]);\n }\n }\n}\n'
(release/'continuation.scad').write_text(text)
old=(repo/'models/sarepta/releases/2026-10-31_lightweight-open-deck/source.scad').read_text()
old=old.replace('part="layout";', 'include <continuation.scad>\npart="assembly";')
a=old.index('module upper_outer()');b=old.index('module hatch_through()',a)
old=old[:a]+'''// Continue the lower outer side at the existing horizontal glue plane.
module upper_outer() { continuation_blank(); }
module upper_hollow() {
    // Conservative XY erosion leaves at least 1.2 mm in the plan normal.
    // The open underside stops 1 mm below the preserved roof height.
    intersection() {
        translate([1.2,0,0]) upper_outer();
        translate([-1.2,0,0]) upper_outer();
        translate([0,1.2,0]) upper_outer();
        translate([0,-1.2,0]) upper_outer();
        translate([-5,-45,join_z-0.05]) cube([180,90,roof_z-skin-join_z+0.05]);
    }
    translate([face_x,-20.65,join_z-0.1]) cube([4000*sf-face_x,41.3,20]);
    translate([4000*sf+1.2,-560*sf,join_z-0.1]) cube([30,1120*sf,20]);
}
'''+old[b:]
a=old.index('module top_skin()');b=old.index('module small_ribs()',a)
old=old[:a]+'''module top_skin() {
    intersection() {
        upper_outer();
        translate([-5,-40,roof_z-skin]) cube([face_x+5,80,skin]);
    }
}
'''+old[b:]
old=old.replace('translate([0,0,2.4]) foredeck_details();','''intersection() {
                translate([0,0,2.4]) foredeck_details();
                linear_extrude(height=40) projection() upper_outer();
            }''')
(release/'source.scad').write_text(old)
(release/'build_continuation.py').write_text(Path('work/analysis/build_continuation.py').read_text())
print('New release:',release,'profile rows:',n,'half volume',volume)
